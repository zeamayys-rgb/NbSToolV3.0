/* ============================================================================
   docs-shell.js — the reading shell of the Help Centre (CMP-35)

   One engine, two pages. help.html holds the authored Help Centre articles;
   technical-docs.html generates the "science behind it" articles from
   js/technical-docs.js. Both read js/docs-index.js and show the same sidebar:
     · the Help Centre tree — five sections in order; an entry page with
       children (the four science pages) expands while it, or one of its
       children, is the open article
     · the search box, which searches every article on both pages and lists
       the matches flat; a match on the other page links there with the query
       still in the box (?q=)
     · one article at a time, routed by the URL hash (#id or #docs/id). On the
       authored page a hash naming a section inside an article opens that
       article and scrolls to the section, so every heading is deep-linkable
     · the "On this page" list, built from the article's .doc-section > h2
     · the previous / next pager, in this page's own article order
   A page only says where its articles come from:

     DocsShell.mount({ page: 'help' });
         Articles are already in the HTML as <div data-doc="id"> children of
         #docs-article. With JavaScript off they all show as one long page;
         with it on the shell lifts them out and shows one at a time.

     DocsShell.mount({ page: 'methodology', render: id => htmlString });
         Articles are generated by a function (js/technical-docs.js).

   Expected markup (both pages): #docs-search, #docs-article-nav,
   #docs-article, and optionally #docs-toc. See SCREENS.md SCR-17 / SCR-19.
   ============================================================================ */

(function () {
  'use strict';

  var state = { page: null, cfg: null, render: null, owner: null, active: null, toc: null };

  function $(sel) { return document.querySelector(sel); }
  function esc(s) {
    return String(s == null ? '' : s).replace(/[&<>"]/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c];
    });
  }
  /* Never animate scrolling for a reader who asked us not to. */
  function scrollBehavior() {
    return window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth';
  }
  function find(page, id) {
    return DOCS_INDEX[page].articles.filter(function (a) { return a.id === id; })[0];
  }
  function query() { var i = $('#docs-search'); return i ? i.value.trim() : ''; }
  function words(q) { return q.toLowerCase().split(/\s+/).filter(Boolean); }

  /* Link to an article. Same page: just the hash. Other page: its URL, carrying
     the search so the reader lands with the same results in the sidebar. */
  function link(page, id, q) {
    var c = DOCS_INDEX[page];
    var base = page === state.page ? '' : c.url + (q ? '?q=' + encodeURIComponent(q) : '');
    return base + '#' + c.hashPrefix + id;
  }

  function matches(a, ws) {
    var text = (a.label + ' ' + a.group + ' ' + a.keywords).toLowerCase();
    return ws.every(function (w) { return text.indexOf(w) !== -1; });
  }

  /* Wrap matched words in <mark>, escaping everything else. */
  function highlight(label, ws) {
    if (!ws.length) return esc(label);
    var re = new RegExp('(' + ws.map(function (w) {
      return w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    }).join('|') + ')', 'ig');
    return label.split(re).map(function (part, i) {
      return i % 2 ? '<mark>' + esc(part) + '</mark>' : esc(part);
    }).join('');
  }

  /* ------------------------------------------------------------- sidebar */
  function heading(label) { return '<div class="docs-nav-group">' + esc(label) + '</div>'; }

  function item(page, a, ws, cls) {
    var current = page === state.page && a.id === state.active;
    return '<a class="docs-nav-button' + (cls || '') + '" href="' + link(page, a.id, ws.length ? query() : '') + '"' +
      (current ? ' aria-current="page"' : '') + '>' + highlight(a.label, ws) + '</a>';
  }

  /* The children of an entry page, from every page of the index. */
  function children(id) {
    var out = [];
    Object.keys(DOCS_INDEX).forEach(function (page) {
      DOCS_INDEX[page].articles.forEach(function (a) {
        if (a.parent === id) out.push({ page: page, a: a });
      });
    });
    return out;
  }

  function renderNav() {
    var host = $('#docs-article-nav');
    if (!host) return;
    var q = query(), ws = words(q), html = '', group = '';

    /* Searching: every matching article on both pages, flat, under its section. */
    if (ws.length) {
      Object.keys(DOCS_INDEX).forEach(function (page) {
        DOCS_INDEX[page].articles.forEach(function (a) {
          if (!matches(a, ws)) return;
          if (a.group && a.group !== group) { group = a.group; html += heading(group); }
          html += item(page, a, ws);
        });
      });
      host.innerHTML = html ||
        '<div class="docs-nav-empty">Nothing in the Help Centre matches &ldquo;' + esc(q) + '&rdquo;.</div>';
      return;
    }

    /* Browsing: the Help Centre tree. An entry page with children expands only
       while it, or one of its children, is the open article. */
    DOCS_INDEX.help.articles.forEach(function (a) {
      if (a.parent) return;
      if (a.group && a.group !== group) { group = a.group; html += heading(group); }
      var kids = children(a.id);
      var open = (state.page === 'help' && a.id === state.active) ||
        kids.some(function (k) { return k.page === state.page && k.a.id === state.active; });
      html += item('help', a, ws, kids.length ? ' docs-nav-parent' + (open ? ' is-open' : '') : '');
      if (kids.length && open) {
        html += '<div class="docs-nav-children">' +
          kids.map(function (k) { return item(k.page, k.a, ws); }).join('') + '</div>';
      }
    });
    host.innerHTML = html;
  }

  /* Keep the current article visible in the sidebar: scrolled into the
     horizontal chip rail on narrow screens, into the sticky column on wide. */
  function keepCurrentInView() {
    var rail = $('#docs-article-nav'), cur = rail && rail.querySelector('[aria-current]');
    if (!cur) return;
    var r = cur.getBoundingClientRect();
    if (rail.scrollWidth > rail.clientWidth) {
      rail.scrollLeft += r.left - rail.getBoundingClientRect().left - 16;
      return;
    }
    var side = rail.closest('.docs-sidebar'), b = side.getBoundingClientRect();
    if (r.top < b.top || r.bottom > b.bottom) side.scrollTop += r.top - b.top - b.height / 3;
  }

  /* --------------------------------------------------------- on this page */
  function scrollToSection(id) {
    var target = document.getElementById(id);
    if (!target) return;
    target.scrollIntoView({ behavior: scrollBehavior(), block: 'start' });
    target.setAttribute('tabindex', '-1');
    target.focus({ preventScroll: true });
  }

  function renderToc() {
    var host = $('#docs-toc'), article = $('#docs-article');
    if (!host || !article) return;
    var heads = [].slice.call(article.querySelectorAll('.doc-section > h2'));
    host.innerHTML = heads.map(function (h) {
      var id = h.parentElement.id;
      return '<a href="#' + id + '" data-doc-toc="' + id + '">' + esc(h.textContent) + '</a>';
    }).join('');
    host.querySelectorAll('a').forEach(function (a) {
      a.addEventListener('click', function (e) { e.preventDefault(); scrollToSection(a.dataset.docToc); });
    });

    if (state.toc) state.toc.disconnect();
    state.toc = new IntersectionObserver(function (entries) {
      var hit = entries.filter(function (x) { return x.isIntersecting; })
        .sort(function (a, b) { return a.boundingClientRect.top - b.boundingClientRect.top; })[0];
      if (!hit) return;
      host.querySelectorAll('a').forEach(function (a) { a.classList.toggle('active', a.dataset.docToc === hit.target.id); });
    }, { rootMargin: '-22% 0px -68% 0px' });
    article.querySelectorAll('.doc-section').forEach(function (s) { state.toc.observe(s); });
  }

  /* --------------------------------------------------------------- pager */
  function renderPager() {
    var list = state.cfg.articles;
    var i = list.indexOf(find(state.page, state.active));
    var prev = list[i - 1], next = list[i + 1];
    function card(a, dir) {
      return a ? '<a href="' + link(state.page, a.id) + '"><span>' + dir + '</span><strong>' + esc(a.label) + '</strong></a>' : '<span></span>';
    }
    $('#docs-article').insertAdjacentHTML('beforeend',
      '<footer class="docs-article-footer">' + card(prev, '&larr; PREVIOUS') + card(next, 'NEXT &rarr;') + '</footer>');
  }

  /* ------------------------------------------------------------- routing */
  function open(id, section) {
    var entry = find(state.page, id) || find(state.page, state.cfg.defaultId);
    state.active = entry.id;

    var host = $('#docs-article');
    var out = state.render(entry.id);
    host.textContent = '';
    if (typeof out === 'string') host.innerHTML = out; else if (out) host.appendChild(out);
    renderPager();
    renderNav();
    keepCurrentInView();
    renderToc();
    /* nav-mobile.js hides unlabelled inline SVGs; re-run for freshly placed markup. */
    if (typeof window.hardenSvgs === 'function') window.hardenSvgs();

    document.title = (entry.label === state.cfg.title ? '' : entry.label + ' · ') + state.cfg.title + ' · NbS Tool';
    /* A section hash stays in the address, so the link a reader copies still
       lands on the heading they are reading. */
    var hash = '#' + state.cfg.hashPrefix + (section || entry.id);
    if (location.hash !== hash && history.replaceState) history.replaceState(null, '', location.pathname + location.search + hash);

    if (section) { scrollToSection(section); return; }
    window.scrollTo({ top: 0, behavior: scrollBehavior() });
    host.focus({ preventScroll: true });
  }

  function idFromHash() {
    var h = decodeURIComponent(location.hash.slice(1)), p = state.cfg.hashPrefix;
    return h.indexOf(p) === 0 ? h.slice(p.length) : '';
  }

  /* An article that moved to another page: forward, keeping the reader's search. */
  function forwardIfMoved(id) {
    var to = state.cfg.moved && state.cfg.moved[id];
    if (to) location.replace(to.replace('#', location.search + '#'));
    return !!to;
  }

  function onHash() {
    var id = idFromHash();
    if (find(state.page, id)) { if (id !== state.active) open(id); return; }
    if (forwardIfMoved(id)) return;
    /* A section inside the open article: a plain in-page link. */
    if (id && document.getElementById(id)) { scrollToSection(id); return; }
    /* A section inside another article: open that article there. Anything
       else is a stale link, which lands on the first article. */
    var owner = id && state.owner ? state.owner(id) : '';
    if (owner) open(owner, id); else open(state.cfg.defaultId);
  }

  /* Articles authored in the page itself: lift them out of the flow so only
     one shows at a time. With scripting off they never move. */
  function staticArticles() {
    var store = {};
    document.querySelectorAll('#docs-article > [data-doc]').forEach(function (el) {
      store[el.dataset.doc] = el;
      /* The id is for the scripting-off page. Left on, the browser would also
         jump to it, landing the reader below the article's heading. */
      el.removeAttribute('id');
      el.remove();
    });
    /* Which article holds a given section id. */
    state.owner = function (sectionId) {
      var hit = '';
      Object.keys(store).forEach(function (id) {
        if (!hit && store[id].querySelector('#' + CSS.escape(sectionId))) hit = id;
      });
      return hit;
    };
    return function (id) { return store[id]; };
  }

  function mount(opts) {
    state.page = opts.page;
    state.cfg = DOCS_INDEX[opts.page];
    state.render = opts.render || staticArticles();

    var input = $('#docs-search');
    var incoming = new URLSearchParams(location.search).get('q');
    if (input) {
      if (incoming) input.value = incoming;
      input.addEventListener('input', renderNav);
    }
    window.addEventListener('hashchange', onHash);
    if (!forwardIfMoved(idFromHash())) onHash();
  }

  window.DocsShell = { mount: mount, open: open, scrollToSection: scrollToSection, scrollBehavior: scrollBehavior };
})();
